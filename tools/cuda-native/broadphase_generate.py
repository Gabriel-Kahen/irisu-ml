#!/usr/bin/env python3
"""Mechanically adapt the vendored r58 SAP methods for the fixed-array port.

The destination header's state/API and checked numeric adapters are maintained
separately. This script emits the order-sensitive integer algorithm bodies.
"""
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
source=ROOT/'third_party/box2d_legacy/Source/Collision/b2BroadPhase.cpp'
s=source.read_text()
def method(signature):
 a=s.index(signature);brace=s.index('{',a);depth=1;i=brace+1
 while depth:
  depth+=(s[i]=='{')-(s[i]=='}');i+=1
 return s[a:i]
def transform(text):
 text=re.sub(r'^\s*b2Assert\([^\n]*\);\n','\n',text,flags=re.M)
 text=text.replace('aabb.IsValid()','valid_aabb(aabb)').replace('memmove','move_bounds').replace(' * sizeof(b2Bound)','')
 text=text.replace('m_pairManager.AddBufferedPair(proxyId, m_queryResults[i]);','m_pairManager.AddBufferedPair(proxyId, m_queryResults[i], error);')
 text=re.sub(r'm_pairManager\.(AddBufferedPair|RemoveBufferedPair)\(([^;]+)\);',lambda m:f'm_pairManager.{m[1]}({m[2]}'+('' if m[2].endswith(', error') else ', error')+');',text)
 text=text.replace('m_pairManager.Commit();','m_pairManager.Commit(m_proxyPool, callback, error);')
 text=text.replace('void* userData','std::uint32_t userData').replace('void** userData','std::uint32_t* userData').replace('NULL','0u')
 text=text.replace('if (s_validate)','if constexpr (false)')
 return text
selected=[('void b2BroadPhase::IncrementTimeStamp()',None),('void b2BroadPhase::IncrementOverlapCount(int32 proxyId)',None),('void b2BroadPhase::Query(int32* lowerQueryOut',None),('uint16 b2BroadPhase::CreateProxy(', 'create'),('void b2BroadPhase::DestroyProxy(', 'destroy'),('void b2BroadPhase::MoveProxy(', 'move'),('int32 b2BroadPhase::Query(const b2AABB&',None),('bool b2BroadPhase::TestOverlap(const b2BoundValues&',None)]
out=[]
for signature,kind in selected:
 text=transform(method(signature))
 if kind=='create':
  text=text.replace('const b2AABB& aabb, std::uint32_t userData)','const b2AABB& aabb, std::uint32_t userData, Callback& callback)')
  text='template<class Callback>\n'+text
  at=text.index('{')+1;text=text[:at]+'''
 if(error!=Status::ok)return b2_nullProxy;
 if(m_proxyCount>=b2_maxProxies||m_freeProxy==b2_nullProxy){error=Status::capacity;return b2_nullProxy;}
 if(!valid_aabb(aabb)){error=Status::unsupported_numeric;return b2_nullProxy;}
'''+text[at:]
  text=text.replace('ComputeBounds(lowerValues, upperValues, aabb);','ComputeBounds(lowerValues, upperValues, aabb);if(error!=Status::ok)return b2_nullProxy;')
 if kind=='destroy':
  text=text.replace('void b2BroadPhase::DestroyProxy(int32 proxyId)','template<class Callback>\nvoid b2BroadPhase::DestroyProxy(int32 proxyId, Callback& callback)');at=text.index('{')+1;text=text[:at]+'''
 if(error!=Status::ok)return;
 if(proxyId<0||proxyId>=b2_maxProxies||!m_proxyPool[proxyId].IsValid()){error=Status::invalid_snapshot;return;}
'''+text[at:]
 if kind=='move':
  at=text.index('{')+1;text=text[:at]+'''
 if(error!=Status::ok)return;
 if(proxyId<0||proxyId>=b2_maxProxies||!m_proxyPool[proxyId].IsValid()){error=Status::invalid_snapshot;return;}
'''+text[at:]
  text=text.replace('if (valid_aabb(aabb) == false)\n\t{', 'if (valid_aabb(aabb) == false)\n\t{error=Status::unsupported_numeric;')
  text=text.replace('ComputeBounds(newValues.lowerValues, newValues.upperValues, aabb);','ComputeBounds(newValues.lowerValues, newValues.upperValues, aabb);if(error!=Status::ok)return;')
 if signature.startswith('int32 b2BroadPhase::Query'):
  text=text.replace('ComputeBounds(lowerValues, upperValues, aabb);','if(error!=Status::ok)return 0;\n ComputeBounds(lowerValues, upperValues, aabb);if(error!=Status::ok)return 0;')
 if signature.startswith('void b2BroadPhase::IncrementOverlapCount'):
  text=text.replace('m_queryResults[m_queryResultCount]', 'if(m_queryResultCount>=b2_maxProxies){error=Status::capacity;return;}\n m_queryResults[m_queryResultCount]')
 text=text.replace('b2BroadPhase::','BroadPhase::').replace('b2AABB','AABB').replace('b2BoundValues','BoundValues').replace('b2Bound','Bound').replace('b2Proxy','Proxy').replace('b2Swap','swap_values')
 text=text.replace('bool BroadPhase::TestOverlap','bool BroadPhase::TestOverlap')
 text=text.replace('void BroadPhase::','NATIVE_HD inline void BroadPhase::').replace('uint16 BroadPhase::','NATIVE_HD inline uint16 BroadPhase::').replace('int32 BroadPhase::','NATIVE_HD inline int32 BroadPhase::').replace('bool BroadPhase::','NATIVE_HD inline bool BroadPhase::')
 out.append(text)
(ROOT/'clone/cuda_native/broadphase_algorithm.inc').write_text('// Altered r58 integer SAP method bodies; generated by broadphase_generate.py.\n'+'\n\n'.join(out)+'\n')
